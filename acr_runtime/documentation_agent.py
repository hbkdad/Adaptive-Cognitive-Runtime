@dataclass(frozen=True)
class DocumentationProposal:
    proposal_id: str
    candidate_dir: str
    source_digest: str
    artifact_hashes: dict[str, str]

    def as_dict(self) -> dict[str, object]:
        return asdict(self)


class DocumentationAgent:
    def __init__(self, repository: str | Path) -> None:
        self.repository = Path(repository).resolve()
        if not (self.repository / "acr_runtime").is_dir():
            raise ValueError("Documentation repository is invalid")

    def render(self) -> tuple[str, dict[str, str]]:
        source_digest = _source_digest(self.repository)
        artifacts = {
            name: GENERATORS[name](self.repository, source_digest)
            for name in ARTIFACTS
        }
        return source_digest, artifacts

    def propose(
        self, candidate_dir: str | Path | None = None
    ) -> DocumentationProposal:
        source_digest, artifacts = self.render()
        hashes = {
            name: _hash_text(content) for name, content in artifacts.items()
        }
        proposal_id = _hash_text(_canonical({
            "generator_version": GENERATOR_VERSION,
            "source_digest": source_digest,
            "artifact_hashes": hashes,
        }))
        target = (
            self.repository
            / ".acr"
            / "documentation-proposals"
            / proposal_id
            if candidate_dir is None
            else Path(candidate_dir).resolve()
        )
        target.mkdir(parents=True, exist_ok=False)
        for name, content in artifacts.items():
            (target / name).write_text(content, encoding="utf-8", newline="\n")
        manifest = {
            "schema_version": 1,
            "generator_version": GENERATOR_VERSION,
            "proposal_id": proposal_id,
            "source_digest": source_digest,
            "artifact_hashes": hashes,
        }
        (target / "manifest.json").write_text(
            json.dumps(manifest, indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
            newline="\n",
        )
        return DocumentationProposal(
            proposal_id, str(target), source_digest, hashes
        )

    @staticmethod
    def _load_manifest(candidate: Path) -> dict[str, object]:
        payload = json.loads(
            (candidate / "manifest.json").read_text(encoding="utf-8")
        )
        required = {
            "schema_version", "generator_version", "proposal_id",
            "source_digest", "artifact_hashes",
        }
        if not isinstance(payload, dict) or set(payload) != required:
            raise ValueError("Documentation manifest shape is invalid")
        if payload["schema_version"] != 1:
            raise ValueError("Unsupported documentation manifest")
        if (
            not isinstance(payload["artifact_hashes"], dict)
            or set(payload["artifact_hashes"]) != set(ARTIFACTS)
        ):
            raise ValueError("Documentation artifact set is invalid")
        return payload

    def review(
        self,
        candidate_dir: str | Path,
        *,
        published_dir: str | Path | None = None,
    ) -> dict[str, object]:
        candidate = Path(candidate_dir).resolve()
        manifest = self._load_manifest(candidate)
        source_digest, current = self.render()
        actual_hashes = {
            name: _hash_bytes((candidate / name).read_bytes())
            for name in ARTIFACTS
        }
        expected_hashes = manifest["artifact_hashes"]
        fresh = (
            manifest["generator_version"] == GENERATOR_VERSION
            and manifest["source_digest"] == source_digest
            and actual_hashes == expected_hashes
            and all(
                (candidate / name).read_text(encoding="utf-8") == current[name]
                for name in ARTIFACTS
            )
        )
        published = (
            self.repository / "docs" / "generated"
            if published_dir is None
            else Path(published_dir).resolve()
        )
        changes = {
            name: (
                "missing"
                if not (published / name).is_file()
                else "unchanged"
                if _hash_bytes((published / name).read_bytes())
                == actual_hashes[name]
                else "changed"
            )
            for name in ARTIFACTS
        }
        review_hash = (
            _hash_text(_canonical({
                "proposal_id": manifest["proposal_id"],
                "source_digest": source_digest,
                "artifact_hashes": actual_hashes,
            }))
            if fresh else None
        )
        return {
            "proposal_id": manifest["proposal_id"],
            "fresh": fresh,
            "review_hash": review_hash,
            "changes": changes,
            "publishable": fresh and any(
                value != "unchanged" for value in changes.values()
            ),
        }

    def publish(
        self,
        candidate_dir: str | Path,
        *,
        review_hash: str,
        approved: bool,
        destination: str | Path | None = None,
    ) -> dict[str, object]:
        if not approved:
            raise PermissionError("Documentation publish requires --approve")
        candidate = Path(candidate_dir).resolve()
        target = (
            self.repository / "docs" / "generated"
            if destination is None
            else Path(destination).resolve()
        )
        review = self.review(candidate, published_dir=target)
        if not review["fresh"] or review["review_hash"] != review_hash:
            raise PermissionError(
                "Documentation review is stale or does not match the proposal"
            )
        target.mkdir(parents=True, exist_ok=True)
        written: list[str] = []
        for name in ARTIFACTS:
            temporary = target / f".{name}.{uuid.uuid4().hex}.tmp"
            temporary.write_bytes((candidate / name).read_bytes())
            os.replace(temporary, target / name)
            written.append(name)
        return {
            "proposal_id": review["proposal_id"],
            "published": written,
            "destination": str(target),
            "review_hash": review_hash,
        }

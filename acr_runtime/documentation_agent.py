def _troubleshooting(root: Path, source_digest: str) -> str:
    lines = _header("Troubleshooting", source_digest)
    lines.extend([
        "Start with:",
        "",
        "```powershell",
        "python -m acr_runtime.cli --db .acr/acr.db doctor --json",
        "python -m acr_runtime.cli --db .acr/acr.db status",
        "```",
        "",
        "| Symptom | Safe next check |",
        "| --- | --- |",
        "| Provider unavailable | Confirm the configured provider and local endpoint; deterministic features remain available. |",
        "| Model timeout | Inspect the retained task failure and retry only when the dependency is healthy. |",
        "| Database locked | Wait for the current writer, then retry; SQLite uses a bounded busy timeout. |",
        "| Schema mismatch | Run `acr doctor`; back up before an explicit migration. |",
        "| FTS unavailable | Check the Python SQLite build reported by `acr doctor`. |",
        "| Invalid or quarantined skill | Run `acr skills validate` and inspect retained validation evidence. |",
        "| Docker sandbox blocked | Verify the image is preinstalled; validation never pulls it. |",
        "| Suspected secret exposure | Run `acr secrets scan-staged` and do not persist the value. |",
        "| Corrupt memory | Stop writes, preserve a backup, inspect integrity, and repair from verified evidence. |",
        "",
        "Do not weaken permissions, bypass review, or auto-repair corrupted state "
        "to make a health check pass.",
    ])
    return "\n".join(lines) + "\n"


